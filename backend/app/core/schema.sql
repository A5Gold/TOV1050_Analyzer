-- -----------------------------------------------------------------------------
-- Table: saved_repeated_exceptions
-- Purpose: Sub-module 2 - Repeated exceptions from HistoryCompareView with Follow-up Action tracking
-- Note: Does NOT store chartData, and MOCK_DATA (id starts with 'mock-') is filtered out
-- 
-- ENHANCEMENT (2026-01-31): Added 9 new workflow columns to align with ComparisonDataGrid:
-- - reoccurrence_id: Links to historical database record (Check 1 year Record feature)
-- - Site Verification group: verify_deadline, verify_date, verify_result, verified_by
-- - Final Adjustment group: adjust_deadline, adjust_date, adjust_result, adjusted_by
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS saved_repeated_exceptions (
    -- Primary Key (auto-increment because same exception can appear in multiple comparison runs)
    record_id INTEGER PRIMARY KEY AUTOINCREMENT,
    exception_id TEXT NOT NULL,               -- Original ExceptionRecord.id (NOT mock-*)
    
    -- Exception Details (inherited from ExceptionRecord)
    exception_type TEXT NOT NULL,
    level TEXT NOT NULL CHECK(level IN ('L1', 'L2', 'L3')),
    from_m REAL NOT NULL,
    to_m REAL NOT NULL,
    length REAL,
    max_value REAL,
    max_location REAL,
    track_type TEXT,
    overlap TEXT,
    tension_length TEXT,
    landmark TEXT,
    class TEXT,
    threshold_value REAL,
    section TEXT,
    
    -- Repeated Exception Specific Fields (from ComparisonDataGrid)
    previous_1 TEXT,                          -- Exception ID from previous analysis (1)
    previous_2 TEXT,                          -- Exception ID from previous analysis (2)
    repeat_count INTEGER DEFAULT 2,           -- Number of times this exception appeared
    
    -- Reoccurrence Tracking (NEW: 2026-01-31)
    reoccurrence_id TEXT,                     -- Links to historical record ID (for Check 1 year Record feature)
    
    -- Initial Check Workflow Fields (EDITABLE)
    action TEXT,                              -- 'Pending', 'Keep monitoring', 'Calculation', 'Verify on site', 'No action required', etc.
    check_date TEXT,                          -- Scheduled check date (YYYY-MM-DD)
    checked_by TEXT,                          -- Person who checked
    check_result TEXT,                         -- Calculation result ('Pass', 'Fail', 'N/A')
    remarks TEXT,                             -- Additional remarks
    
    -- Site Verification Workflow Fields (NEW: 2026-01-31)
    verify_deadline TEXT,                     -- Verification deadline (YYYY-MM-DD)
    verify_date TEXT,                         -- Actual verification date (YYYY-MM-DD)
    verify_result TEXT,                       -- Verification result ('Pass', 'Fail', 'N/A')
    verified_by TEXT,                         -- Person who verified
    
    -- Final Adjustment Workflow Fields (NEW: 2026-01-31)
    adjust_deadline TEXT,                     -- Adjustment deadline (YYYY-MM-DD)
    adjust_date TEXT,                         -- Actual adjustment date (YYYY-MM-DD)
    adjust_result TEXT,                       -- Adjustment result ('Pass', 'Fail', 'N/A')
    adjusted_by TEXT,                         -- Person who adjusted
    
    -- Task Run Data (identifies the comparison context)
    line TEXT NOT NULL,
    track TEXT NOT NULL,
    date_str TEXT NOT NULL,                   -- Latest analysis date (YYYYMMDD)
    task_run_date TEXT,                       -- Task run date (YYYY/MM/DD format for display, stored as ISO)
    
    -- Optional Metadata
    task_no TEXT,
    station_start TEXT,
    station_end TEXT,
    
    -- Comparison Source Reference
    latest_file_name TEXT,                    -- Name of latest Excel file in comparison
    comparison_files TEXT,                    -- JSON array of file names used in comparison
    
    -- System Fields
    saved_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    saved_by TEXT,
    last_updated DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    -- Prevent duplicate saves of the same repeated exception
    UNIQUE(exception_id, line, track, date_str)
);

