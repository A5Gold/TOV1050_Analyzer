-- -----------------------------------------------------------------------------
-- View: v_sessions_with_stats
-- Purpose: Sessions with exception statistics (denormalized for dashboard)
-- -----------------------------------------------------------------------------
CREATE VIEW IF NOT EXISTS v_sessions_with_stats AS
SELECT 
    s.id,
    s.line,
    s.section,
    s.track,
    s.date_str,
    s.status,
    s.created_at,
    s.analyzed_at,
    s.total_exceptions,
    s.l1_count,
    s.l2_count,
    s.l3_count,
    s.task_no,
    s.station_start,
    s.station_end,
    s.raw_data_file_name,
    -- Calculated fields
    COALESCE(
        (SELECT COUNT(*) FROM exceptions e 
         WHERE e.session_id = s.id AND e.current_status = 'pending'), 0
    ) AS pending_count,
    COALESCE(
        (SELECT COUNT(*) FROM exceptions e 
         WHERE e.session_id = s.id AND e.current_status = 'in_progress'), 0
    ) AS in_progress_count,
    COALESCE(
        (SELECT COUNT(*) FROM exceptions e 
         WHERE e.session_id = s.id AND e.current_status = 'resolved'), 0
    ) AS resolved_count
FROM analysis_sessions s
ORDER BY s.created_at DESC;

-- -----------------------------------------------------------------------------
-- View: v_pending_critical_exceptions
-- Purpose: All pending L1 (critical) exceptions across all sessions
-- -----------------------------------------------------------------------------
CREATE VIEW IF NOT EXISTS v_pending_critical_exceptions AS
SELECT 
    e.id,
    e.session_id,
    e.exception_type,
    e.level,
    e.from_m,
    e.to_m,
    e.max_value,
    e.current_status,
    e.priority,
    e.assigned_to,
    e.created_at,
    s.line,
    s.track,
    s.section,
    s.date_str
FROM exceptions e
JOIN analysis_sessions s ON e.session_id = s.id
WHERE e.level = 'L1' 
  AND e.current_status IN ('pending', 'in_progress')
ORDER BY 
    e.priority DESC,
    e.created_at ASC;

-- -----------------------------------------------------------------------------
-- View: v_repeated_exception_summary_by_date
-- Purpose: Aggregate repeated exception statistics by date and line
-- NOTE: Renamed from v_exception_summary_by_date (2026-01-31)
-- -----------------------------------------------------------------------------
CREATE VIEW IF NOT EXISTS v_repeated_exception_summary_by_date AS
SELECT 
    line,
    track,
    date_str,
    COUNT(*) AS total_count,
    SUM(CASE WHEN level = 'L1' THEN 1 ELSE 0 END) AS l1_count,
    SUM(CASE WHEN level = 'L2' THEN 1 ELSE 0 END) AS l2_count,
    SUM(CASE WHEN level = 'L3' THEN 1 ELSE 0 END) AS l3_count,
    MIN(saved_at) AS first_saved,
    MAX(saved_at) AS last_saved
FROM saved_repeated_exceptions
GROUP BY line, track, date_str
ORDER BY date_str DESC;

-- -----------------------------------------------------------------------------
-- View: v_pending_repeated_exceptions
-- Purpose: Repeated exceptions requiring follow-up action
-- -----------------------------------------------------------------------------
CREATE VIEW IF NOT EXISTS v_pending_repeated_exceptions AS
SELECT 
    record_id,
    exception_id,
    exception_type,
    level,
    from_m,
    to_m,
    max_value,
    line,
    track,
    date_str,
    action,
    repeat_count,
    check_date,
    checked_by,
    saved_at,
    last_updated
FROM saved_repeated_exceptions
WHERE action IN ('Pending', 'Keep monitoring', NULL, '')
   OR (action = 'Calculation' AND (check_result IS NULL OR check_result = ''))
ORDER BY 
    CASE level 
        WHEN 'L1' THEN 1 
        WHEN 'L2' THEN 2 
        WHEN 'L3' THEN 3 
    END,
    saved_at DESC;

