-- -----------------------------------------------------------------------------
-- Trigger: trg_sessions_update_timestamp
-- Purpose: Auto-update last_modified when analysis_sessions is updated
-- -----------------------------------------------------------------------------
CREATE TRIGGER IF NOT EXISTS trg_sessions_update_timestamp
AFTER UPDATE ON analysis_sessions
FOR EACH ROW
BEGIN
    UPDATE analysis_sessions 
    SET last_modified = CURRENT_TIMESTAMP 
    WHERE id = NEW.id;
END;

-- -----------------------------------------------------------------------------
-- Trigger: trg_exceptions_status_change
-- Purpose: Record status changes in exception_history table
-- -----------------------------------------------------------------------------
CREATE TRIGGER IF NOT EXISTS trg_exceptions_status_change
AFTER UPDATE OF current_status ON exceptions
FOR EACH ROW
WHEN OLD.current_status <> NEW.current_status
BEGIN
    INSERT INTO exception_history (exception_id, old_status, new_status, changed_at)
    VALUES (NEW.id, OLD.current_status, NEW.current_status, CURRENT_TIMESTAMP);
    
    -- Also update last_modified on the exception
    UPDATE exceptions 
    SET last_modified = CURRENT_TIMESTAMP 
    WHERE id = NEW.id;
END;

-- -----------------------------------------------------------------------------
-- Trigger: trg_increment_db_version
