-- -----------------------------------------------------------------------------
-- Table: analysis_sessions
-- Purpose: Store analysis session metadata (auto-created on each analysis run)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS analysis_sessions (
    id TEXT PRIMARY KEY,                      -- UUID (generated by backend)
    
    -- Analysis Metadata
    line TEXT NOT NULL,                       -- EAL / TML / etc.
    section TEXT NOT NULL,                    -- Mainline / RAC / LOW / LMC
    track TEXT NOT NULL,                      -- UP / DOWN
    date_str TEXT NOT NULL,                   -- Analysis date (YYYYMMDD)
    
    -- File Reference (raw data NOT stored, only path reference)
    raw_data_file_path TEXT,                  -- Full path to .datac file
    raw_data_file_name TEXT,                  -- Original filename
    raw_data_file_size INTEGER,               -- File size in bytes
    
    -- Optional Metadata
    task_no TEXT,                             -- User-defined task number
    station_start TEXT,                       -- Start station name
    station_end TEXT,                         -- End station name
    
    -- Analysis Statistics (denormalized for quick access)
    total_exceptions INTEGER DEFAULT 0,
    l1_count INTEGER DEFAULT 0,               -- Critical
    l2_count INTEGER DEFAULT 0,               -- Warning
    l3_count INTEGER DEFAULT 0,               -- Info
    
    -- Status Management
    status TEXT DEFAULT 'completed' CHECK(status IN ('pending', 'completed', 'failed', 'archived')),
    
    -- Timestamps
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    analyzed_at DATETIME,
    last_modified DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    -- Indexable Constraints
    UNIQUE(line, track, date_str, section, raw_data_file_name)
);

-- -----------------------------------------------------------------------------
-- Table: exceptions
-- Purpose: Store individual exception records (auto-saved during analysis)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exceptions (
    id TEXT PRIMARY KEY,                      -- UUID (from ExceptionRecord.id)
    session_id TEXT NOT NULL,                 -- FK to analysis_sessions
    
    -- Exception Details (mirrors ExceptionRecord interface)
    exception_type TEXT NOT NULL,             -- 'Low Height', 'High Height', 'Wire Wear', 'Stagger Left', 'Stagger Right'
    level TEXT NOT NULL CHECK(level IN ('L1', 'L2', 'L3')),
    from_m REAL NOT NULL,                     -- Start chainage (meters)
    to_m REAL NOT NULL,                       -- End chainage (meters)
    length REAL,                              -- Exception length
    max_value REAL,                           -- Peak value
    max_location REAL,                        -- Location of peak value
    
    -- Track Classification
    track_type TEXT,                          -- Track type classification
    overlap TEXT,                             -- Overlap zone information
    tension_length TEXT,                      -- Tension length value
    landmark TEXT,                            -- Nearest landmark
    class TEXT,                               -- Classification (both, LMC, etc.)
    threshold_value REAL,                     -- Applied threshold value
    section TEXT,                             -- Section classification
    
    -- Workflow Status (for Stateful management)
    current_status TEXT DEFAULT 'pending' CHECK(current_status IN ('pending', 'in_progress', 'resolved', 'deferred', 'false_positive')),
    assigned_to TEXT,                         -- Person responsible
    notes TEXT,                               -- General notes
    priority INTEGER DEFAULT 0,               -- 0=Normal, 1=High, 2=Critical
    
    -- Resolution Tracking
    resolved_at DATETIME,
    resolved_by TEXT,
    resolution_notes TEXT,
    
    -- Timestamps
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    last_modified DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    -- Foreign Key
    FOREIGN KEY (session_id) REFERENCES analysis_sessions(id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- Table: exception_history
-- Purpose: Track status changes for audit trail
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS exception_history (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    exception_id TEXT NOT NULL,               -- FK to exceptions
    
    -- Change Record
    old_status TEXT,
    new_status TEXT NOT NULL,
    changed_by TEXT,                          -- Who made the change
    change_reason TEXT,                       -- Why the change was made
    
    -- Metadata
    changed_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    -- Foreign Key
    FOREIGN KEY (exception_id) REFERENCES exceptions(id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- Table: reports
-- Purpose: Track report generation history
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS reports (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id TEXT NOT NULL,                 -- FK to analysis_sessions
    
    -- Report Details
    report_type TEXT NOT NULL CHECK(report_type IN ('excel', 'pdf', 'csv', 'json')),
    file_name TEXT NOT NULL,
    file_path TEXT,
    file_size INTEGER,
    
    -- Report Metadata
    generated_by TEXT,
    include_charts INTEGER DEFAULT 1,         -- Boolean: include chart data
    include_metadata INTEGER DEFAULT 1,       -- Boolean: include __metadata__ sheet
    
    -- Version Control (for Excel sync)
    db_version_at_export INTEGER,             -- Database version when exported
    schema_version TEXT,                      -- Schema version
    
    -- Timestamps
    generated_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    
    -- Foreign Key
    FOREIGN KEY (session_id) REFERENCES analysis_sessions(id) ON DELETE SET NULL
);

