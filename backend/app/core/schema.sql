-- -----------------------------------------------------------------------------
-- Trigger: trg_update_session_stats
-- Purpose: Update denormalized exception counts on analysis_sessions
-- -----------------------------------------------------------------------------
CREATE TRIGGER IF NOT EXISTS trg_update_session_stats_insert
AFTER INSERT ON exceptions
FOR EACH ROW
BEGIN
    UPDATE analysis_sessions
    SET 
        total_exceptions = (SELECT COUNT(*) FROM exceptions WHERE session_id = NEW.session_id),
        l1_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = NEW.session_id AND level = 'L1'),
        l2_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = NEW.session_id AND level = 'L2'),
        l3_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = NEW.session_id AND level = 'L3'),
        last_modified = CURRENT_TIMESTAMP
    WHERE id = NEW.session_id;
END;

CREATE TRIGGER IF NOT EXISTS trg_update_session_stats_delete
AFTER DELETE ON exceptions
FOR EACH ROW
BEGIN
    UPDATE analysis_sessions
    SET 
        total_exceptions = (SELECT COUNT(*) FROM exceptions WHERE session_id = OLD.session_id),
        l1_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = OLD.session_id AND level = 'L1'),
        l2_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = OLD.session_id AND level = 'L2'),
        l3_count = (SELECT COUNT(*) FROM exceptions WHERE session_id = OLD.session_id AND level = 'L3'),
        last_modified = CURRENT_TIMESTAMP
    WHERE id = OLD.session_id;
